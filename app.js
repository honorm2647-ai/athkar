const state = {
  tab: "morning",
  counts: {}, // key: `${tab}:${id}` -> done number
  search: "",
  fontScale: 100,
};

const grid = document.getElementById("cardsGrid");
const progressText = document.getElementById("progressText");
const progressFill = document.getElementById("progressFill");
const totalCountEl = document.getElementById("totalCount");
const completeBanner = document.getElementById("completeBanner");
const searchInput = document.getElementById("searchInput");
const timeBadge = document.getElementById("timeBadge");
const toastEl = document.getElementById("toast");

function todayKey(){
  const d = new Date();
  return d.toISOString().slice(0,10);
}
function storageKey(){ return "athkari-progress-" + todayKey(); }
function load(){
  try{
    const theme = localStorage.getItem("athkari-theme");
    if(theme) document.documentElement.setAttribute("data-theme", theme);
    else if(window.matchMedia("(prefers-color-scheme: dark)").matches) document.documentElement.setAttribute("data-theme","dark");
    const fs = parseInt(localStorage.getItem("athkari-font")||"100",10);
    if(!isNaN(fs)) state.fontScale = Math.min(160,Math.max(70,fs));
    const saved = JSON.parse(localStorage.getItem(storageKey())||"{}");
    state.counts = saved;
    const hour = new Date().getHours();
    state.tab = (hour>=12 && hour<18) ? "evening" : (hour>=18||hour<4) ? "evening" : "morning";
    // default morning if early; evening after noon? Use simple: morning 4-15, evening otherwise
    if(hour>=4 && hour<15) state.tab="morning"; else state.tab="evening";
  }catch(e){}
}
function save(){
  localStorage.setItem(storageKey(), JSON.stringify(state.counts));
  localStorage.setItem("athkari-font", String(state.fontScale));
}
function applyThemeUI(){
  const t = document.documentElement.getAttribute("data-theme");
  document.getElementById("themeIcon").textContent = t==="dark" ? "☀️" : "🌙";
  document.querySelector(".theme-text").textContent = t==="dark" ? "نهاري" : "ليلي";
}
function applyFont(){
  const px = (state.fontScale/100*1.35);
  document.documentElement.style.setProperty("--dhikr-size", px.toFixed(2)+"rem");
  document.getElementById("fontSizeLabel").textContent = state.fontScale+"%";
}
function filteredList(){
  return ATHKAR.filter(a=>a.cats.includes(state.tab))
    .filter(a=>{
      if(!state.search) return true;
      return (a.title+a.text+(a.textEvening||"")).includes(state.search.trim());
    });
}
function keyFor(id){ return state.tab+":"+id; }
function getDone(item){ return Math.min(item.repeat, state.counts[keyFor(item.id)]||0); }
function getRemaining(item){ return item.repeat - getDone(item); }

function render(){
  document.querySelectorAll(".tab").forEach(b=>{
    const active = b.dataset.tab===state.tab;
    b.classList.toggle("active", active);
    b.setAttribute("aria-selected", active?"true":"false");
  });
  timeBadge.textContent = state.tab==="morning" ? "🌅 أذكار الصباح" : "🌙 أذكار المساء";
  const list = filteredList();
  grid.innerHTML = "";
  list.forEach((item, idx)=>{
    const done = getDone(item);
    const rem = getRemaining(item);
    const isDone = rem===0;
    const pct = item.repeat===0?100:Math.round(done/item.repeat*100);
    const displayText = (state.tab==="evening" && item.textEvening) ? item.textEvening : item.text;
    const card = document.createElement("article");
    card.className = "card"+(isDone?" completed":"");
    card.innerHTML = `
      <div class="card-head">
        <span class="num">${idx+1}</span>
        <h3>${item.title}</h3>
        <span class="repeat-badge">${item.repeat===1?"مرة واحدة":item.repeat+" مرات"}</span>
      </div>
      <p class="dhikr-text ${item.quran?"quran":""}">${displayText}</p>
      <div class="meta">
        <div class="virtue">✨ <strong>الفضل:</strong> ${item.virtue}</div>
        <div class="source">📚 <strong>المصدر:</strong> ${item.source}</div>
      </div>
      <div class="counter">
        <div class="ring" style="--p:${item.repeat? (rem/item.repeat*100):0}"><span>${rem===0?"✓":rem}</span></div>
        <button class="tasbih-btn" ${isDone?"disabled":""}>${isDone?"تم بحمد الله ✓":"سبِّح • بقي "+rem}</button>
        <div class="mini-btns">
          <button class="mini-btn undo" title="تراجع عن واحدة">↩</button>
          <button class="mini-btn reset-one" title="تصفير هذا الذكر">↺</button>
        </div>
      </div>
      <div><span class="done-tag">✓ مكتمل — ${done}/${item.repeat}</span>
      ${!isDone && done>0 ? `<span style="color:var(--muted);font-size:.85rem">أنجزت ${done} من ${item.repeat}</span>`:""}</div>
    `;
    const btn = card.querySelector(".tasbih-btn");
    btn.addEventListener("click", ()=>{
      if(getRemaining(item)<=0) return;
      const k = keyFor(item.id);
      state.counts[k]=(state.counts[k]||0)+1;
      save(); render();
      if(getRemaining(item)===0){
        showToast("تقبّل الله — أتممت: "+item.title);
        if(navigator.vibrate) navigator.vibrate(60);
      }
    });
    card.querySelector(".undo").addEventListener("click", ()=>{
      const k=keyFor(item.id);
      state.counts[k]=Math.max(0,(state.counts[k]||0)-1);
      save(); render();
    });
    card.querySelector(".reset-one").addEventListener("click", ()=>{
      delete state.counts[keyFor(item.id)];
      save(); render();
    });
    grid.appendChild(card);
  });
  document.getElementById("emptyState").classList.toggle("hidden", list.length!==0);

  const totalCards = filteredList().length;
  // for progress use all (not search filtered? use tab total)
  const allTab = ATHKAR.filter(a=>a.cats.includes(state.tab));
  const doneCards = allTab.filter(a=>getRemaining(a)===0).length;
  const totalLeft = allTab.reduce((s,a)=>s+getRemaining(a),0);
  const totalRepeats = allTab.reduce((s,a)=>s+a.repeat,0);
  const doneRepeats = totalRepeats-totalLeft;
  progressText.textContent = `${doneCards} من ${allTab.length} مكتمل • ${doneRepeats}/${totalRepeats} تسبيحة`;
  progressFill.style.width = (allTab.length? (doneCards/allTab.length*100):0)+"%";
  totalCountEl.textContent = totalLeft===0 ? "كل الأذكار مكتملة 🎉" : `${totalLeft} تسبيحة متبقية`;
  completeBanner.classList.toggle("hidden", !(allTab.length>0 && doneCards===allTab.length));
}

let toastTimer;
function showToast(msg){
  toastEl.textContent=msg;
  toastEl.classList.remove("hidden");
  clearTimeout(toastTimer);
  toastTimer=setTimeout(()=>toastEl.classList.add("hidden"),2200);
}

